	inline constexpr std::uint32_t kUtilityTechniqueStart = 0x2B;
	inline constexpr std::uint32_t kRenderShadowmap = 1U << 14;

	/** Only lightless utility shadow-map draws can discard the borrowed light-array pointer. */
	constexpr bool IsIsolatedShadowPass(bool a_utility, std::uint32_t a_technique, std::uint8_t a_lights, std::uint8_t a_shadowLights)
	{
		return a_utility && a_technique >= kUtilityTechniqueStart &&
		       ((a_technique - kUtilityTechniqueStart) & kRenderShadowmap) != 0 && a_lights == 0 && a_shadowLights == 0;
	}

	/** Match native VR bucket selection without touching the renderer's technique map. */
	constexpr std::uint32_t BucketIndex(std::uint64_t a_geometryShaderFlags, std::uint16_t a_alphaFlags)
	{
		return (a_geometryShaderFlags & (1ULL << 54)) != 0 ? 4U :
		                                                     static_cast<std::uint32_t>((a_geometryShaderFlags >> 35) & 2U) | ((a_alphaFlags >> 9) & 1U);
	}

	constexpr std::uint64_t BucketKey(std::uint32_t a_technique, std::uint32_t a_bucket)
	{
		return (static_cast<std::uint64_t>(a_technique) << 32) | a_bucket;
	}

