	constexpr bool Matches(std::span<const std::uint8_t> a_code, const HookSite& a_site)
	{
		if (a_code.size() < a_site.prefix.size())
			return false;
		for (std::size_t i = 0; i < a_site.prefix.size(); ++i) {
			if (a_code[i] != a_site.prefix[i])
				return false;
		}
		return true;
	}
