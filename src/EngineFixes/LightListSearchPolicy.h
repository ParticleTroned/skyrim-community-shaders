#pragma once

#include <algorithm>
#include <array>
#include <cstddef>
#include <cstdint>
#include <span>

namespace LightListSearch::Policy
{
	inline constexpr std::size_t MinimumVectorCount = 16;
	inline constexpr std::size_t NativeCodeSize = 0x16C;

	/** @brief Only the -1 fence returns duplicates without modifying list state. */
	constexpr bool ShouldSearch(std::int32_t a_fence, std::size_t a_count) noexcept
	{
		return a_fence == -1 && a_count >= MinimumVectorCount;
	}

	/** @brief Verify the entry, duplicate-only branch and side-effect-free return path. */
	inline bool MatchesNativeCode(std::span<const std::uint8_t> a_code) noexcept
	{
		constexpr std::array<std::uint8_t, 57> prefix{
			0x48, 0x89, 0x54, 0x24, 0x10, 0x41, 0x56, 0x48, 0x83, 0xEC, 0x50,
			0x48, 0xC7, 0x44, 0x24, 0x30, 0xFE, 0xFF, 0xFF, 0xFF,
			0x48, 0x89, 0x5C, 0x24, 0x60, 0x48, 0x89, 0x74, 0x24, 0x70, 0x48, 0x89, 0x7C, 0x24, 0x78,
			0x48, 0x8B, 0xFA, 0x48, 0x8B, 0xD9, 0x44, 0x8B, 0x51, 0x18,
			0x33, 0xC0, 0x41, 0x83, 0xFA, 0xFF, 0x0F, 0x84, 0xAE, 0x00, 0x00, 0x00
		};
		constexpr std::array<std::uint8_t, 43> duplicate{
			0x41, 0x83, 0xC8, 0xFF, 0x44, 0x8B, 0x49, 0x10, 0x45, 0x85, 0xC9, 0x74, 0x1E,
			0x41, 0x83, 0xF8, 0xFF, 0x75, 0x5C, 0x48, 0x8B, 0x11, 0x48, 0x39, 0x3C, 0xC2,
			0x44, 0x0F, 0x44, 0xC0, 0xFF, 0xC0, 0x41, 0x3B, 0xC1, 0x72, 0xE8,
			0x41, 0x83, 0xF8, 0xFF, 0x75, 0x44
		};
		constexpr std::array<std::uint8_t, 22> epilogue{
			0x48, 0x8B, 0x5C, 0x24, 0x60, 0x48, 0x8B, 0x74, 0x24, 0x70, 0x48, 0x8B, 0x7C, 0x24, 0x78,
			0x48, 0x83, 0xC4, 0x50, 0x41, 0x5E, 0xC3
		};
		return a_code.size() >= NativeCodeSize &&
		       std::ranges::equal(a_code.first(prefix.size()), prefix) &&
		       std::ranges::equal(a_code.subspan(0xE7, duplicate.size()), duplicate) &&
		       std::ranges::equal(a_code.subspan(0x156, epilogue.size()), epilogue);
	}
}
